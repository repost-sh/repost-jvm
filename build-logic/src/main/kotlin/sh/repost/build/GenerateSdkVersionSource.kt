package sh.repost.build

import org.gradle.api.DefaultTask
import org.gradle.api.Project
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.plugins.JavaPluginExtension
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import org.gradle.kotlin.dsl.configure
import org.gradle.kotlin.dsl.register
import org.gradle.work.DisableCachingByDefault
import java.nio.charset.StandardCharsets
import java.nio.file.Files

/**
 * Generates the `SdkVersion` class of one package: the build's version
 * (repostVersion in gradle.properties) as a compile-time constant, so the code
 * reports the version its artifact is published at, from a jar, a shaded jar or
 * a native image alike.
 */
@DisableCachingByDefault(because = "Writing one constant is cheaper than a cache round trip")
abstract class GenerateSdkVersionSource : DefaultTask() {
    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val sdkVersion: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val root = outputDirectory.get().asFile
        root.deleteRecursively()
        val source = root.toPath()
            .resolve(packageName.get().replace('.', '/'))
            .resolve("SdkVersion.java")
        Files.createDirectories(source.parent)
        Files.write(
            source,
            """
            |// Generated by the JVM build from repostVersion in gradle.properties. DO NOT EDIT.
            |package ${packageName.get()};
            |
            |/** The SDK release version this artifact is published at. */
            |public final class SdkVersion {
            |    /** The release version, as in the artifact's coordinates. */
            |    public static final String VALUE = "${sdkVersion.get()}";
            |
            |    private SdkVersion() {
            |    }
            |}
            |""".trimMargin().toByteArray(StandardCharsets.UTF_8),
        )
    }
}

/** Compiles the generated `SdkVersion` class of [packageName], at the project's version, into its main sources. */
fun Project.addSdkVersionSource(packageName: String) {
    val source = tasks.register<GenerateSdkVersionSource>("generateSdkVersionSource") {
        this.packageName.set(packageName)
        sdkVersion.set(provider { version.toString() })
        outputDirectory.set(layout.buildDirectory.dir("generated/sources/sdkVersion/java/main"))
    }
    extensions.configure<JavaPluginExtension> {
        sourceSets.named("main") { java.srcDir(source) }
    }
}
